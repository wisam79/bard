/**
 * Get a contextually appropriate emoji for a product based on its name.
 * Uses a 3-layer matching strategy for maximum accuracy.
 */
export const getProductEmoji = (name: string, category?: string): string => {
  if (!name) return '📦';
  const n = name.toLowerCase().trim();

  // ── Layer 1: Exact keyword match ──
  for (const [keywords, emoji] of KEYWORD_MAP) {
    for (const keyword of keywords) {
      if (n.includes(keyword)) return emoji;
    }
  }

  // ── Layer 2: Stem / root matching ──
  for (const [stem, emoji] of STEM_MAP) {
    if (n.includes(stem)) return emoji;
  }

  // ── Layer 3: Category fallback ──
  if (category) {
    const cat = category.toLowerCase().trim();
    for (const [key, emoji] of Object.entries(CATEGORY_MAP)) {
      if (cat.includes(key) || key.includes(cat)) return emoji;
    }
  }

  // ── Layer 4: Smart generic fallback based on common suffixes/patterns ──
  if (/\d+\s*(مل|لتر|ml|l|لتر|غ|جم|كغ|kg|g|غرام|جرام)/.test(n)) return '🧴'; // has size notation → likely a liquid or packaged product
  if (/\d+\s*(قطع|حب|حبة|عدد|قطعة)/.test(n)) return '📦'; // count-based → generic package
  if (n.length <= 3) return '🏷️'; // Very short name → label/tag

  return '📦';
};
